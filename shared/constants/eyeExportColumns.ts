const standardKeys: ReadonlySet<string> = new Set(EYE_EXPORT_STANDARD_KEYS)
export const isStandardEyeExportKey = (value: unknown): value is string =>
  typeof value === 'string' && (standardKeys.has(value) || (value.startsWith('subject_info::') && value.length > 'subject_info::'.length))
